// P5：库·我的、体检子页、修改版（含启用确认、修改版管理、版本条）。
import { check, gotoPage, modalCount, settle } from './helpers.mjs'
import { callStore } from './store.mjs'
import { sw } from './suite-library.mjs'

export async function mineSuite(page, label) {
  const row = (name) => page.locator('[data-testid^="mine-row-"]').filter({ hasText: name }).first()
  await gotoPage(page, '库')
  await page.getByRole('button', { name: '我的', exact: true }).click()
  await page.getByTestId('mine-tab').waitFor()
  const copyName = '万象无常书（我的）'
  check(`[${label}] 我的：复制出的包在列表里，带版本号与「编辑 ›」`, (await row(copyName).innerText()).includes('v1.0.0') && (await row(copyName).getByRole('button', { name: '编辑 ›' }).isVisible()))

  await row(copyName).getByRole('button', { name: '编辑 ›' }).click()
  await page.getByTestId('mine-sub').waitFor()
  await page.locator('.trpg-vlist__row').first().waitFor()
  const n0 = Number((await page.getByText(/共 \d+ 条/).innerText()).match(/\d+/)[0])
  check(`[${label}] 编辑 ›：进入子页（顶部「‹ 我的」），列出条目`, (await page.getByRole('button', { name: '我的', exact: true }).count()) >= 1 && n0 > 100, `${n0}`)
  check(`[${label}] 条目编辑器未提供时「编辑」按钮灰显并说明`, (await page.locator('.trpg-vlist__row').first().getByRole('button', { name: '编辑' }).isDisabled()))
  const firstName = (await page.locator('.trpg-vlist__row .trpg-term').first().innerText()).trim()
  await page.locator('.trpg-vlist__row').first().getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '复制' }).click()
  await settle(page, 500)
  check(`[${label}] 条目「⋯」→ 复制：条目数加 1`, Number((await page.getByText(/共 \d+ 条/).innerText()).match(/\d+/)[0]) === n0 + 1)
  await page.locator('.trpg-vlist__row').first().getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '删除' }).click()
  await settle(page)
  check(`[${label}] 删除条目：确认页换页显示，不叠加弹窗`, (await modalCount(page)) === 1 && (await page.locator('.trpg-modal').innerText()).includes('删除'))
  await page.getByRole('button', { name: '删除', exact: true }).last().click()
  await settle(page, 600)
  check(`[${label}] 确认后条目数回落（${firstName}）`, Number((await page.getByText(/共 \d+ 条/).innerText()).match(/\d+/)[0]) === n0)
  await page.getByRole('button', { name: '我的', exact: true }).first().click()
  await page.getByTestId('mine-tab').waitFor()

  // 新建、改名、删除、回收站
  await page.getByTestId('mine-new').click()
  await page.getByRole('textbox', { name: '名称' }).fill('我的资料')
  await page.getByRole('button', { name: '建立' }).click()
  await page.getByText('已建立「我的资料」').waitFor()
  check(`[${label}] ＋ 新建：弹窗建立，提示并出现在列表`, (await modalCount(page)) === 0 && (await row('我的资料').count()) === 1)
  await row('我的资料').getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '改名与简介' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill('我的房规')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await settle(page, 400)
  check(`[${label}] 改名与简介`, (await row('我的房规').count()) === 1 && (await row('我的资料').count()) === 0)
  await row('我的房规').getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '删除' }).click()
  await settle(page)
  check(`[${label}] 删除我的包：确认文字写明「库回收站保留 30 天」`, (await page.locator('.trpg-modal').innerText()).includes('30 天'))
  await page.getByRole('button', { name: '删除', exact: true }).last().click()
  await page.getByText(/已删除「我的房规」/).waitFor()
  await settle(page, 400)
  check(`[${label}] 删除后进入库回收站（1）`, (await row('我的房规').count()) === 0 && (await page.getByRole('heading', { name: '库回收站（1）' }).isVisible()))
  await page.getByRole('button', { name: '恢复', exact: true }).click()
  await page.getByText('已恢复「我的房规」').waitFor()
  await settle(page, 500)
  check(`[${label}] 从回收站恢复`, (await row('我的房规').count()) === 1 && (await page.getByRole('heading', { name: /库回收站/ }).count()) === 0)
  await row('我的房规').getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '删除' }).click()
  await page.getByRole('button', { name: '删除', exact: true }).last().click()
  await page.getByRole('heading', { name: '库回收站（1）' }).waitFor()
  await page.getByRole('button', { name: '彻底删除', exact: true }).click()
  await settle(page)
  check(`[${label}] 彻底删除前再确认一次（弹窗内一页）`, (await modalCount(page)) === 1 && (await page.locator('.trpg-modal').innerText()).includes('永久删除'))
  await page.getByRole('button', { name: '彻底删除', exact: true }).last().click()
  await page.getByRole('heading', { name: /库回收站/ }).waitFor({ state: 'detached' })
  check(`[${label}] 彻底删除后回收站清空`, (await page.getByRole('heading', { name: /库回收站/ }).count()) === 0)
}

export async function healthSuite(page, label) {
  await callStore(page, 'campaign', (s) => s.updateData((d) => ({ ...d, instances: [...d.instances, { id: 'h1', type: 't', name: '体检测试', data: { ref: { $ref: 'pack', packId: 'ghost', entryId: 'x', name: '幽灵' } } }] })))
  await gotoPage(page, '库')
  await page.getByRole('button', { name: '扩展', exact: true }).click()
  await page.getByRole('button', { name: '本存档', exact: true }).click()
  await page.getByTestId('go-health').waitFor({ timeout: 15000 })
  check(`[${label}] 体检：本存档顶部出现「发现 1 处问题」`, (await page.locator('.trpg-issuerow').innerText()).includes('发现 1 处问题'))
  await page.getByTestId('go-health').click()
  await page.getByTestId('health-page').waitFor()
  check(`[${label}] 去处理 ›：进入体检子页，列出问题与修复按钮`, (await page.getByTestId('health-issue').count()) === 1 && (await page.getByRole('button', { name: '改为纯文字' }).isVisible()) && (await page.getByRole('button', { name: '去安装' }).isVisible()))
  await page.getByRole('button', { name: '改为纯文字' }).click()
  await page.getByText('已修复').waitFor()
  await settle(page, 400)
  check(`[${label}] 修复后自动重新检查：没有问题`, (await page.getByText('体检：没有问题').isVisible()))
  await page.getByRole('button', { name: '本存档', exact: true }).first().click()
  check(`[${label}] 返回本存档后问题行消失`, (await page.locator('.trpg-issuerow').count()) === 0)
}

export async function variantsSuite(page, label, { fixture }) {
  await gotoPage(page, '库')
  await page.getByRole('button', { name: '本存档', exact: true }).click()
  await page.locator('input[type=file]').first().setInputFiles(fixture)
  await page.getByTestId('import-pack').waitFor()
  await page.getByRole('button', { name: '安装', exact: true }).click()
  await page.getByText('已安装「测试修改版包」').first().waitFor()
  await page.getByRole('button', { name: '完成' }).click()
  await settle(page, 400)
  const pack = sw(page, '启用 测试修改版包')
  await pack.waitFor()
  check(`[${label}] 导入带修改版的包后，本存档里出现它（开关为关）`, (await pack.getAttribute('aria-checked')) === 'false')
  await pack.click()
  await page.getByTestId('apply-variants').waitFor()
  check(`[${label}] 启用带修改版的包：先弹出确认，列出将应用的修改，只有一个弹窗`, (await modalCount(page)) === 1 && (await page.getByTestId('apply-variants').innerText()).includes('修改了 1 个官方条目'))
  await page.getByRole('button', { name: '启用', exact: true }).click()
  await page.getByText('已启用「测试修改版包」').waitFor()
  await settle(page, 500)
  check(`[${label}] 启用后：开关为开，出现「修改版」行与新的规则选项`, (await pack.getAttribute('aria-checked')) === 'true' && (await page.locator('.trpg-variantrow').innerText()).includes('1 个条目用了修改版') && (await page.getByTestId('option-测试规则选项').count()) === 1)
  await page.getByTestId('go-variants').click()
  await page.getByTestId('variants-page').waitFor()
  check(`[${label}] 修改版子页：来源汇总「测试修改版包 · 1 处 · 使用中 1」`, (await page.getByTestId('variants-page').innerText()).includes('1 处 · 使用中 1'))
  const select = page.getByRole('combobox', { name: /使用的版本/ })
  check(`[${label}] 条目行显示当前使用的版本`, (await select.innerText()).includes('测试修改版包'))
  await select.click()
  await page.getByRole('option', { name: '原版' }).click()
  await settle(page, 500)
  check(`[${label}] 改用原版：即时生效，汇总变为「使用中 0」`, (await page.getByTestId('variants-page').innerText()).includes('使用中 0'))
  await page.getByRole('button', { name: '全部使用' }).click()
  await settle(page, 500)
  check(`[${label}] 「全部使用」：改回使用中 1`, (await page.getByTestId('variants-page').innerText()).includes('使用中 1'))
  await page.getByRole('button', { name: '全部不用' }).click()
  await settle(page)
  check(`[${label}] 「全部不用」：先在窗口里确认并列出会改回的条目`, (await modalCount(page)) === 1 && (await page.locator('.trpg-modal').innerText()).includes('会改回'))
  await page.getByRole('button', { name: '全部不用', exact: true }).last().click()
  await settle(page, 500)
  check(`[${label}] 确认后：使用中 0，候选保留`, (await page.getByTestId('variants-page').innerText()).includes('使用中 0'))
  await page.getByRole('button', { name: '全部使用' }).click()
  await settle(page, 500)

  // 条目详情里的版本条
  await page.locator('[data-testid^="variant-"] .trpg-term').first().click()
  await page.getByTestId('variant-bar').waitFor()
  check(`[${label}] 条目详情顶部显示版本条（使用修改版）`, (await page.getByTestId('variant-bar').innerText()).includes('测试修改版包'))
  await page.getByRole('button', { name: '切换版本' }).click()
  await page.getByRole('radio', { name: '原版' }).check()
  await settle(page, 600)
  check(`[${label}] 版本条「切换版本」：改用原版，版本条文字同步`, (await page.getByTestId('variant-bar').innerText()).includes('本存档使用原版'))
  await page.keyboard.press('Escape')
  await page.locator('.trpg-modal__close').click()
  await settle(page, 400)

  // 停用：改回的条目先列出
  await page.getByRole('button', { name: /^本存档$/ }).first().click().catch(() => undefined)
  await gotoPage(page, '库')
  await page.getByRole('button', { name: '本存档', exact: true }).click()
  await page.getByTestId('go-variants').click()
  await page.getByRole('button', { name: '全部使用' }).click()
  await settle(page, 400)
  await page.getByRole('button', { name: '本存档', exact: true }).first().click()
  await sw(page, '启用 测试修改版包').click()
  await settle(page)
  check(`[${label}] 停用带修改版的包：确认页列出「改回原版」的条目与功能状态说明`, (await modalCount(page)) === 1 && (await page.locator('.trpg-modal').innerText()).includes('改回原版'))
  await page.getByRole('button', { name: '停用', exact: true }).last().click()
  await page.getByText('已停用「测试修改版包」').waitFor()
  await settle(page, 400)
  check(`[${label}] 停用后「修改版」行消失，规则选项隐藏`, (await page.locator('.trpg-variantrow').count()) === 0 && (await page.getByTestId('option-测试规则选项').count()) === 0)
  await gotoPage(page, '首页')
}
