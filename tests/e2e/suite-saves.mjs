// P4：页头保存、存档抽屉（战役卡片）、读取确认、导出与导入、设置里的备份提醒、只读窗口、没有聊天。
import { writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { check, gotoPage, modalCount, settle } from './helpers.mjs'
import { callStore, makeDirty } from './store.mjs'

async function openDrawer(page, narrow) {
  if (narrow) {
    await page.getByRole('button', { name: '助手 的更多操作' }).click()
    await page.getByRole('menuitem', { name: '存档' }).click()
  } else await page.getByTestId('save-chip').click()
  await page.getByTestId('save-drawer').waitFor()
  await settle(page, 350)
}

const rowOf = (page, name) => page.getByTestId(`save-${name}`)
/** 根存档在界面上叫「战役起点」，它的 ⋯ 菜单也用这个名字。 */
const menuOf = (page, name, root = false) => page.getByRole('button', { name: `${root ? '战役起点' : name} 的更多操作` })
const campCount = (page) => page.locator('.trpg-camp .trpg-saves li').count()

export async function savesSuite(page, label, { width, url }) {
  const narrow = width <= 480
  await gotoPage(page, '首页')

  // 页头保存
  await makeDirty(page)
  const saveBtn = page.getByTestId('save-button')
  await saveBtn.waitFor()
  check(`[${label}] 有未保存改动：页头出现「保存」，横幅写「● 有未保存到存档的改动」`, (await saveBtn.isVisible()) && (await page.getByTestId('banner-state').innerText()).includes('有未保存到存档的改动'))
  await saveBtn.click()
  await page.getByText('已保存存档', { exact: true }).waitFor()
  check(`[${label}] 点「保存」：提示「已保存存档」，按钮消失`, (await page.getByTestId('save-button').count()) === 0)
  await makeDirty(page)
  await page.locator('.trpg-content').click({ position: { x: 5, y: 5 } })
  await page.keyboard.press('ControlOrMeta+s')
  await settle(page, 400)
  check(`[${label}] ⌘/Ctrl+S 保存`, (await page.getByTestId('save-button').count()) === 0)

  // 整块横幅是一个点击区 → 抽屉
  await page.getByTestId('banner').click()
  await page.getByTestId('save-drawer').waitFor()
  await settle(page, 350)
  const drawer = await page.locator('.trpg-modal__card').boundingBox()
  check(`[${label}] 点横幅打开存档抽屉：${narrow ? '窄屏底部抽屉' : '右侧宽 440px'}，只有一个弹窗`, (await modalCount(page)) === 1 && (narrow ? Math.round(drawer.width) === width : Math.round(drawer.width) === 440), JSON.stringify(drawer))
  check(`[${label}] 抽屉：当前存档条 + 一张战役卡片（战役名 = 根存档名），卡里第一行叫「战役起点」`, (await page.getByTestId('drawer-current').innerText()).includes('当前存档：测试战役') && (await page.locator('.trpg-camp').count()) === 1 && (await page.locator('.trpg-camp').first().innerText()).includes('战役起点'))
  check(`[${label}] 当前存档标「当前」，没有读取按钮；卡头没有读取按钮`, (await rowOf(page, '测试战役').locator('.trpg-badge', { hasText: '当前' }).count()) === 1 && (await rowOf(page, '测试战役').getByRole('button', { name: '读取' }).count()) === 0 && (await page.locator('.trpg-camp summary').getByRole('button', { name: '读取' }).count()) === 0)
  check(`[${label}] 当前战役有未选中的删除提示：当前存档的「删除」不可点，写明「请先读取别的存档」`, await (async () => { await menuOf(page, '测试战役', true).click(); const item = page.getByRole('menuitem', { name: /删除/ }); const ok = (await item.getAttribute('data-disabled')) !== null && (await item.innerText()).includes('请先读取别的存档'); await page.keyboard.press('Escape'); return ok })())
  check(`[${label}] 有战役时抽屉底部是「新建战役」「导入存档」`, (await page.getByTestId('drawer-new').isVisible()) && (await page.getByTestId('drawer-import').isVisible()))

  // 新建分支存档（弹出卡）
  await page.getByTestId('branch-button').click()
  const branchName = page.getByRole('textbox', { name: '新存档名' })
  check(`[${label}] 新建分支存档卡：默认名「测试战役 分支」，一句话说明"开一条新时间线"`, (await branchName.inputValue()) === '测试战役 分支' && (await page.getByText('开一条新时间线').isVisible()))
  await branchName.fill('分支一')
  await branchName.press('Enter')
  await page.getByText('已切换到「分支一」').waitFor()
  await settle(page, 300)
  check(`[${label}] 创建并切换：卡里出现两个存档，当前是「分支一」，写着「来自「测试战役」」`, (await campCount(page)) === 2 && (await rowOf(page, '分支一').locator('.trpg-badge', { hasText: '当前' }).count()) === 1 && (await rowOf(page, '分支一').innerText()).includes('来自「测试战役」'))

  // 改战役名（卡头 ⋯）、备注
  await page.getByRole('button', { name: '测试战役 的更多操作' }).click()
  await page.getByRole('menuitem', { name: '改战役名' }).click()
  const campName = page.getByRole('textbox', { name: '战役名' })
  await campName.fill('旧战役')
  await campName.press('Enter')
  await settle(page, 500)
  check(`[${label}] 卡头 ⋯ 改战役名：战役名 = 根存档名跟着变`, (await page.locator('.trpg-camp .trpg-camp__name').first().innerText()).startsWith('旧战役') && (await rowOf(page, '旧战役').count()) === 1)
  await menuOf(page, '分支一').click()
  await page.getByRole('menuitem', { name: '备注' }).click()
  await page.getByRole('textbox', { name: '备注' }).fill('第一章的存档')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await settle(page, 300)
  check(`[${label}] 备注：保存后显示在行下`, (await rowOf(page, '分支一').innerText()).includes('第一章的存档'))
  await menuOf(page, '分支一').click()
  await page.getByRole('menuitem', { name: '改名' }).click()
  await page.getByRole('textbox', { name: '存档名' }).fill('分支甲')
  await page.keyboard.press('Enter')
  await settle(page, 300)
  check(`[${label}] 行内改名：回车保存`, (await rowOf(page, '分支甲').count()) === 1)

  // 删除有子分支的存档：先说清后果；确认后进最近删除，提示条可撤销
  await menuOf(page, '旧战役', true).click()
  await page.getByRole('menuitem', { name: '删除' }).click()
  await settle(page, 400)
  check(`[${label}] 删除有分支的存档：抽屉内换页写明"分支会变成独立战役"，不叠加弹窗`, (await modalCount(page)) === 1 && (await page.getByText(/会变成独立战役/).isVisible()))
  await page.keyboard.press('Escape')
  await settle(page, 300)
  check(`[${label}] Esc 取消回到抽屉，存档还在`, (await page.getByTestId('save-drawer').isVisible()) && (await rowOf(page, '旧战役').count()) === 1)
  await menuOf(page, '旧战役', true).click()
  await page.getByRole('menuitem', { name: '删除' }).click()
  await page.getByRole('button', { name: '删除', exact: true }).last().click()
  await page.getByText('已删除「旧战役」').waitFor()
  check(`[${label}] 确认删除：移入最近删除，提示条带「撤销」`, (await rowOf(page, '旧战役').count()) === 0 && (await page.getByRole('button', { name: '撤销', exact: true }).isVisible()) && (await page.getByTestId('fold-deleted').count()) === 1)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await settle(page, 500)
  check(`[${label}] 撤销：存档回到卡片里`, (await rowOf(page, '旧战役').count()) === 1)

  // 再删除 → 最近删除 → 彻底删除（二次确认在抽屉内换页）
  await menuOf(page, '旧战役', true).click()
  await page.getByRole('menuitem', { name: '删除' }).click()
  await page.getByRole('button', { name: '删除', exact: true }).last().click()
  await settle(page, 500)
  await page.getByTestId('fold-deleted').locator('summary').click()
  await page.getByTestId('fold-deleted').getByRole('button', { name: '彻底删除', exact: true }).first().click()
  await settle(page)
  check(`[${label}] 彻底删除：确认页在抽屉内换页，写明无法恢复，不叠加弹窗`, (await modalCount(page)) === 1 && (await page.getByText('将被永久删除，无法恢复。').isVisible()))
  await page.keyboard.press('Escape')
  await settle(page)
  check(`[${label}] Esc 取消确认回到抽屉，「最近删除」还在`, (await page.getByTestId('save-drawer').isVisible()) && (await page.getByTestId('fold-deleted').count()) === 1)
  await page.getByTestId('fold-deleted').getByRole('button', { name: '彻底删除', exact: true }).first().click()
  await page.getByRole('button', { name: '彻底删除', exact: true }).last().click()
  await settle(page, 500)
  check(`[${label}] 确认后彻底删除，「最近删除」消失；分支「分支甲」变成独立战役的起点`, (await page.getByTestId('fold-deleted').count()) === 0 && (await page.locator('.trpg-camp .trpg-camp__name').first().innerText()).startsWith('分支甲'))

  // 再开一个分支，改一点内容，然后读取回「分支甲」：读取确认页（合并成一页）
  await page.getByTestId('branch-button').click()
  await page.getByRole('textbox', { name: '新存档名' }).fill('分支乙')
  await page.getByRole('textbox', { name: '新存档名' }).press('Enter')
  await page.getByText('已切换到「分支乙」').waitFor()
  await settle(page, 300)
  await page.locator('.trpg-modal__close').click()
  await makeDirty(page, '读取前的改动')
  await openDrawer(page, narrow)
  await rowOf(page, '分支甲').getByRole('button', { name: '读取' }).click()
  await page.getByTestId('load-confirm').waitFor()
  await settle(page, 400)
  check(`[${label}] 读取：抽屉内换成一页确认（只显示适用的块），还没有读取`, (await modalCount(page)) === 1 && (await page.getByTestId('load-dirty').isVisible()) && (await page.getByTestId('load-lead').innerText()).includes('分支甲') && (await callStore(page, 'campaign', (s) => s.currentSave?.name)) === '分支乙')
  check(`[${label}] 有未保存改动：「先保存再读取」默认选中，另一项「不保存，直接读取」`, (await page.getByTestId('load-dirty').locator('.trpg-check[data-on="true"]').innerText()).includes('先保存') && (await page.getByTestId('load-dirty').innerText()).includes('不保存，直接读取'))
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await settle(page, 300)
  check(`[${label}] 取消：回到抽屉，当前存档没变`, (await page.getByTestId('save-drawer').isVisible()) && (await rowOf(page, '分支乙').locator('.trpg-badge', { hasText: '当前' }).isVisible()))
  await rowOf(page, '分支甲').getByRole('button', { name: '读取' }).click()
  await page.getByTestId('load-go').click()
  await page.getByText('已读取「分支甲」').waitFor()
  await settle(page, 400)
  check(`[${label}] 读取：先保存再读取，弹窗关闭，当前存档变为「分支甲」`, (await modalCount(page)) === 0 && (await callStore(page, 'campaign', (s) => s.currentSave?.name)) === '分支甲')
  await openDrawer(page, narrow)
  check(`[${label}] 读取前自动写入自动存档（折叠区「自动存档」出现）`, (await page.getByTestId('fold-auto').count()) === 1)

  // 读取确认页：「不自动备份当前存档」勾选，记住；勾上后读取不再写自动存档
  const autoCount = () => callStore(page, 'app', async (st) => (await st.svc().db.saves.toArray()).filter((x) => x.kind === 'auto').length)
  await rowOf(page, '分支乙').getByRole('button', { name: '读取' }).click()
  await page.getByTestId('load-confirm').waitFor()
  const skip = page.getByTestId('load-skip-auto')
  check(`[${label}] 读取确认页：有「不自动备份当前存档」勾选，默认没勾`, (await skip.isVisible()) && (await skip.getAttribute('data-on')) === 'false')
  await skip.click()
  await settle(page, 400)
  check(`[${label}] 勾上：说明文字同步，设置里记住`, (await page.getByTestId('load-lead').innerText()).includes('读取前不会自动备份当前内容') && (await callStore(page, 'app', (st) => st.settings?.skipAutoSaveOnLoad)) === true)
  const autosBefore = await autoCount()
  await page.getByTestId('load-go').click()
  await page.getByText('已读取「分支乙」').waitFor()
  await settle(page, 400)
  check(`[${label}] 勾了不备份：读取后没有多出自动存档`, (await autoCount()) === autosBefore)
  await openDrawer(page, narrow)
  await rowOf(page, '分支甲').getByRole('button', { name: '读取' }).click()
  await page.getByTestId('load-confirm').waitFor()
  check(`[${label}] 记住了：下次打开读取确认页仍是勾上的`, (await page.getByTestId('load-skip-auto').getAttribute('data-on')) === 'true')
  await page.getByTestId('load-skip-auto').click()
  await settle(page, 300)
  check(`[${label}] 取消勾选：设置存回关，并恢复"先自动存一份"的说明`, (await callStore(page, 'app', (st) => st.settings?.skipAutoSaveOnLoad)) === false && (await page.getByTestId('load-lead').innerText()).includes('当前内容会先自动存一份'))
  await page.getByTestId('load-go').click()
  await page.getByText('已读取「分支甲」').waitFor()
  await settle(page, 400)
  await openDrawer(page, narrow)

  // 导出
  await menuOf(page, '分支甲', true).click()
  await page.getByRole('menuitem', { name: '导出' }).click()
  await page.getByRole('button', { name: '导出', exact: true }).waitFor()
  await settle(page)
  check(`[${label}] 导出：抽屉先关闭，再打开导出窗口（只有一个弹窗）`, (await modalCount(page)) === 1 && (await page.getByTestId('save-drawer').count()) === 0)
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '导出', exact: true }).click()])
  const exported = join(tmpdir(), `e2e-${label.replace(/\//g, '-')}.trpgsave`)
  await download.saveAs(exported)
  check(`[${label}] 导出文件名以 .trpgsave 结尾`, download.suggestedFilename().endsWith('.trpgsave'), download.suggestedFilename())
  await page.getByText(/已导出「/).waitFor()
  check(`[${label}] 导出后弹窗关闭并提示`, (await modalCount(page)) === 0)

  // 导入：存档文件 → 预览 → 导入 → 结果页
  await openDrawer(page, narrow)
  await page.locator('input[type=file]').setInputFiles(exported)
  await page.getByTestId('import-save').waitFor()
  await settle(page)
  check(`[${label}] 导入存档文件：抽屉关闭，打开导入窗口并识别出 1 个存档`, (await modalCount(page)) === 1 && (await page.getByText('已识别：存档文件 · 1 个存档').isVisible()))
  await page.getByRole('button', { name: '导入 1 个' }).click()
  await page.getByTestId('import-result').waitFor()
  const result = await page.getByTestId('import-result').innerText()
  check(`[${label}] 导入结果页：导入 1 个存档，并写明依赖核对结果（不再是"依赖未核对"）`, result.includes('导入 1 个存档') && !result.includes('依赖未核对'), result)
  await page.getByRole('button', { name: '完成', exact: true }).click()
  await openDrawer(page, narrow)
  check(`[${label}] 导入后出现「分支甲（导入）」（独立战役，卡片默认折叠）`, (await rowOf(page, '分支甲（导入）').count()) === 1)

  // 错误文件、拖放
  const junk = join(tmpdir(), `junk-${label.replace(/\//g, '-')}.trpgsave`)
  writeFileSync(junk, '这不是存档文件')
  await page.locator('input[type=file]').setInputFiles(junk)
  await page.getByRole('alert').waitFor()
  check(`[${label}] 错误文件：显示原因，提供「选择其他文件」与「关闭」`, (await page.getByRole('alert').innerText()).includes('无法识别') && (await page.getByRole('button', { name: '选择其他文件' }).isVisible()))
  await page.getByRole('button', { name: '关闭', exact: true }).first().click()
  await settle(page)
  await openDrawer(page, narrow)
  const dt = await page.evaluateHandle(() => { const d = new DataTransfer(); d.items.add(new File(['拖进来的不是存档'], 'drop.trpgsave')); return d })
  await page.getByTestId('save-drawer').dispatchEvent('dragover', { dataTransfer: dt })
  check(`[${label}] 拖入文件：抽屉显示「松开以导入」`, (await page.getByTestId('save-drawer').getAttribute('data-dragging')) === 'true')
  await page.getByTestId('save-drawer').dispatchEvent('drop', { dataTransfer: dt })
  await page.getByRole('alert').waitFor()
  check(`[${label}] 松开后打开导入窗口并识别（这里是无法识别的文件，显示原因）`, (await page.getByTestId('import-filename').innerText()) === 'drop.trpgsave' && (await modalCount(page)) === 1)
  await page.getByRole('button', { name: '关闭', exact: true }).first().click()
  await settle(page)

  // 设置 › 备份与撤销：提醒可以关（存 0）、可以重新打开
  await gotoPage(page, '设置')
  await page.getByTestId('settings-backup').click()
  await page.getByTestId('backup-settings').waitFor()
  const days = page.getByTestId('setting-reminderDays')
  check(`[${label}] 备份与撤销：三项设置（天数 / 次数 / 撤销上限），天数默认 7 天`, (await page.locator('[data-testid^=setting-]').count()) === 3 && (await days.innerText()).includes('7 天'))
  await days.getByRole('switch').click()
  await settle(page, 400)
  check(`[${label}] 关掉天数提醒：显示「不提醒」，设置里存成 0`, (await days.innerText()).includes('不提醒') && (await callStore(page, 'app', (s) => s.settings?.reminderDays)) === 0)
  await days.getByRole('switch').click()
  await settle(page, 400)
  check(`[${label}] 重新打开：回到默认 7 天`, (await days.innerText()).includes('7 天') && (await callStore(page, 'app', (s) => s.settings?.reminderDays)) === 7)
  await page.getByTestId('setting-undoLimit').getByRole('button', { name: /增加/ }).click()
  await settle(page, 300)
  check(`[${label}] 撤销记录上限：加一档（+10）写进设置`, (await callStore(page, 'app', (s) => s.settings?.undoLimit)) === 60)
  await page.getByTestId('setting-undoLimit').getByRole('button', { name: /减少/ }).click()
  await settle(page, 300)
  await page.getByTestId('settings-back').click()
  await gotoPage(page, '首页')

  // 没有聊天
  await page.evaluate(() => { const c = window.SillyTavern.getContext(); c.characterId = undefined; return c.eventSource.emit('chat_id_changed') })
  await page.getByTestId('no-chat').waitFor()
  check(`[${label}] 未打开聊天：首页提示先打开聊天，没有「开始」横幅`, (await page.getByTestId('no-chat').innerText()).includes('请先在酒馆中打开一个聊天') && (await page.getByTestId('start-banner').count()) === 0)
  await page.evaluate(() => { const c = window.SillyTavern.getContext(); c.characterId = 0; return c.eventSource.emit('chat_id_changed') })
  await page.getByTestId('banner-title').waitFor()
  check(`[${label}] 回到聊天：战役数据自动载入`, (await page.getByTestId('banner-title').innerText()) === '分支甲')
  const homeBox = await page.evaluate(() => {
    const root = document.getElementById('trpg-assistant-root').shadowRoot
    const banner = root.querySelector('.trpg-banner')
    return { bannerH: banner.getBoundingClientRect().height, bannerPos: getComputedStyle(banner).position }
  })
  check(`[${label}] 首页样式在位：横幅高度受限（≤200px）`, homeBox.bannerH > 100 && homeBox.bannerH <= 200 && homeBox.bannerPos === 'relative', JSON.stringify(homeBox))

  // 第二个窗口：只读
  const second = await page.context().newPage()
  await second.goto(url)
  await second.locator('.trpg-ball').click()
  await second.getByRole('button', { name: '只读' }).waitFor({ timeout: 30000 }).catch(() => undefined)
  const roBadge = await second.getByRole('button', { name: '只读' }).count()
  const roToast = await second.getByText('另一个窗口正在使用助手，这里只能查看').count()
  check(`[${label}] 第二个窗口进入只读：页头有「只读」徽章并提示一次`, roBadge === 1 && roToast >= 1, `徽章 ${roBadge}，提示 ${roToast}`)
  await second.close()
  await gotoPage(page, '首页')
}
