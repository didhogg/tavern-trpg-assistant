// U6 人物管理页面（UNIT1）端到端：列表、模板、临时人物卡、多选、标签、回收站、队伍页、存库。
import { check, clearToasts, gotoPage, modalCount, settle } from './helpers.mjs'

const row = (page, name) => page.locator('[data-testid^="people-row-"]').filter({ hasText: name }).first()

export async function peopleSuite(page, label) {
  await gotoPage(page, '人物')
  await page.getByTestId('people-page').waitFor()
  check(`[${label}] 人物页有固定分类：全部/队伍/NPC/敌人`, (await page.locator('[data-testid^="people-category-"]').count()) === 4)

  // 1. 新建：不保存返回 = 不存在；保存才进列表
  await page.getByTestId('people-new').click()
  await page.getByTestId('person-card').waitFor()
  await page.getByTestId('person-card-back').click()
  await page.getByTestId('people-page').waitFor()
  check(`[${label}] 新人物不保存返回，列表不增加`, (await page.locator('[data-testid^="people-row-"]').count()) === 0)
  await page.getByTestId('people-new').click()
  await page.getByTestId('person-card-name').fill('测试勇者')
  await page.getByTestId('person-card-save').click()
  await page.getByText('已保存').waitFor()
  await page.getByTestId('people-page').waitFor()
  check(`[${label}] 保存后列表出现新人物`, (await row(page, '测试勇者').count()) === 1)

  // 5. 排序与当前分类离开页面再回来仍保留
  await page.getByTestId('people-category-npc').click()
  await page.getByRole('combobox', { name: '排序' }).click()
  await page.getByRole('option', { name: '名称' }).click()
  await settle(page, 200)
  await gotoPage(page, '首页')
  await gotoPage(page, '人物')
  await page.getByTestId('people-page').waitFor()
  check(`[${label}] 分类与排序重开后恢复`, (await page.getByTestId('people-category-npc').getAttribute('aria-selected')) === 'true' && (await page.getByRole('combobox', { name: '排序' }).innerText()).includes('名称'))
  await page.getByTestId('people-category-all').click()
  await page.getByRole('combobox', { name: '排序' }).click()
  await page.getByRole('option', { name: '修改时间' }).click()

  // 2. 模板：看资料卡、数量 3、加入列表、弹窗不关
  await page.getByTestId('people-category-all').click()
  await page.getByTestId('people-template').click()
  await page.getByTestId('template-picker').waitFor()
  await page.getByRole('button', { name: /^筛选/ }).click()
  await page.getByTestId('template-filter').waitFor()
  await page.getByRole('checkbox', { name: /SRD 基础规则/ }).check()
  await page.getByRole('combobox', { name: '最高挑战等级' }).click()
  await page.getByRole('option', { name: '2' }).last().click()
  await page.getByRole('button', { name: /完成，显示/ }).click()
  await page.getByRole('searchbox', { name: '搜模板名字' }).fill('地精')
  await page.getByTestId('tpl-row-monster.goblin.mm').click()
  await page.getByTestId('entry-detail').waitFor({ timeout: 5000 })
  check(`[${label}] 点模板行右侧显示资料卡`, (await page.getByTestId('entry-detail').innerText()).includes('地精'))
  await page.getByTestId('tpl-count').fill('3')
  await page.getByTestId('tpl-add').click()
  await page.getByText(/已加入 地精、地精 2、地精 3/).waitFor()
  check(`[${label}] 模板加入后弹窗不关`, await page.getByTestId('template-picker').isVisible())
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await settle(page, 250)
  check(`[${label}] 加入后关闭模板自动切到敌人分类`, (await page.getByTestId('people-category-enemy').getAttribute('aria-selected')) === 'true')
  check(`[${label}] 加入后新行高亮`, ((await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精' }).first().getAttribute('class')) ?? '').includes('is-highlight'))
  check(`[${label}] 敌人分类有地精、地精 2、地精 3 且生命 7/7`, (await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精' }).count()) === 3 && (await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精' }).first().innerText()).includes('7/7'))

  // 3. 模板「编辑后加入」→ 临时人物卡已填名字，保存后数值来自模板
  await clearToasts(page)
  await page.getByTestId('people-template').click()
  await page.getByTestId('template-picker').waitFor()
  await page.getByRole('searchbox', { name: '搜模板名字' }).fill('地精头目')
  await page.getByTestId('tpl-row-monster.goblin-boss.mm').click()
  await page.getByTestId('tpl-edit-add').click()
  await page.getByTestId('person-card').waitFor()
  check(`[${label}] 编辑后加入打开临时人物卡且名字已填`, (await page.getByTestId('person-card-name').inputValue()) === '地精头目')
  await page.getByTestId('person-card-save').click()
  await page.getByText('已保存').waitFor()
  await settle(page, 1200)
  await page.getByTestId('people-page').waitFor()
  await page.getByTestId('people-category-enemy').click()
  const boss = row(page, '地精头目')
  check(`[${label}] 编辑后加入的人生命/AC 来自模板`, (await boss.innerText()).includes('21/21') && (await boss.innerText()).includes('AC 17'))

  // 4. 置顶：行尾菜单，当前分类和「全部」都在最前，取消后回排序位置
  await boss.getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '置顶' }).click()
  await clearToasts(page)
  check(`[${label}] 置顶后当前分类第一行是地精首领`, (await page.locator('[data-testid^="people-row-"]').first().innerText()).includes('地精头目'))
  await page.getByTestId('people-category-all').click()
  check(`[${label}] 置顶的人在全部分类仍第一`, (await page.locator('[data-testid^="people-row-"]').first().innerText()).includes('地精头目'))
  await page.locator('[data-testid^="people-row-"]').first().getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '取消置顶' }).click()
  await clearToasts(page)

  // 5. 多选：送到 NPC、加标签、去标签、删除撤销
  await page.getByTestId('people-category-enemy').click()
  await page.getByTestId('people-select').click()
  await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 2' }).first().locator('input[type=checkbox]').check()
  await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 3' }).first().locator('input[type=checkbox]').check()
  check(`[${label}] 多选栏显示已选 2 人`, (await page.getByTestId('people-selection-bar').innerText()).includes('已选 2 人'))
  await page.getByRole('button', { name: '送到NPC' }).click()
  await page.getByRole('button', { name: '完成', exact: true }).click()
  await clearToasts(page)
  check(`[${label}] 送到 NPC 后从敌人分类消失`, (await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 2' }).count()) === 0)
  await page.getByTestId('people-category-npc').click()
  check(`[${label}] NPC 分类收到地精 2`, (await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 2' }).count()) === 1)
  await page.getByTestId('people-select').click()
  await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 2' }).first().locator('input[type=checkbox]').check()
  await page.getByRole('button', { name: '加标签' }).click()
  await page.getByTestId('tag-editor-add').waitFor()
  await page.getByTestId('tag-editor-input').fill('冒险者')
  await page.getByRole('button', { name: /新建并添加/ }).click()
  await page.getByTestId('tag-editor-add').getByRole('button', { name: '关闭' }).click()
  await clearToasts(page)
  check(`[${label}] 多选加标签后行内出现标签`, (await row(page, '地精 2').innerText()).includes('冒险者'))
  await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 2' }).first().locator('input[type=checkbox]').check()
  await page.getByRole('button', { name: '去标签' }).click()
  await page.getByTestId('tag-editor-remove').waitFor()
  await page.getByTestId('tag-editor-remove').getByRole('button', { name: /冒险者/ }).click()
  await page.getByTestId('tag-editor-remove').getByRole('button', { name: '关闭' }).click()
  await clearToasts(page)
  await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 2' }).first().locator('input[type=checkbox]').check()
  await page.getByRole('button', { name: '删除', exact: true }).last().click()
  await page.getByText(/已移到回收站：1 人/).waitFor()
  await page.getByRole('button', { name: '撤销' }).click()
  await clearToasts(page)
  await page.getByRole('button', { name: '完成', exact: true }).click()
  check(`[${label}] 删除后撤销恢复`, (await page.locator('[data-testid^="people-row-"]').filter({ hasText: '地精 2' }).count()) === 1)

  // 6. 回收站：恢复所选、彻底删除所选（原地确认）
  await page.getByTestId('people-page-menu').getByRole('button', { name: /的人物页面/ }).click().catch(async () => { await page.getByTestId('people-page-menu').getByRole('button', { name: /更多操作/ }).click() })
  await page.getByRole('menuitem', { name: /回收站/ }).click()
  await page.getByTestId('trash-page').waitFor()
  check(`[${label}] 回收站打开且只有一层弹窗`, (await modalCount(page)) === 1)
  await page.getByTestId('trash-page').getByRole('button', { name: '关闭' }).click()

  // 7. 标签筛选与标签管理
  await page.getByTestId('people-category-all').click()
  await page.getByTestId('people-tag-filter').getByRole('combobox').click()
  await page.getByRole('option', { name: '冒险者' }).click()
  await clearToasts(page)
  check(`[${label}] 标签筛选显示共 N 人与清除`, (await page.locator('.trpg-people__filters').count()) === 1)
  await page.getByTestId('people-clear').click()
  await page.getByTestId('people-page-menu').getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '标签管理' }).click()
  await page.getByTestId('tag-manage').waitFor()
  check(`[${label}] 标签管理打开`, (await page.getByTestId('tag-manage').innerText()).includes('冒险者'))
  await page.getByTestId('tag-manage').getByRole('button', { name: '关闭' }).click()

  // 8. 队伍页：队伍名与成员列
  await page.getByTestId('people-category-party').click()
  await page.getByTestId('people-party-name').waitFor()
  await page.getByRole('button', { name: '改名' }).click()
  await page.getByRole('textbox', { name: '队伍名' }).fill('测试小队')
  await page.getByRole('textbox', { name: '队伍名' }).press('Enter')
  await clearToasts(page)
  await page.getByTestId('people-category-all').click()
  await page.getByTestId('people-category-party').click()
  check(`[${label}] 队伍改名后切走再回来仍在`, (await page.getByTestId('people-party-name').innerText()).includes('测试小队'))

  // 9. 键盘 / 聚焦搜索
  await page.getByTestId('people-category-all').click()
  await page.keyboard.press('/')
  check(`[${label}] 按 / 聚焦搜索`, await page.getByTestId('people-search').evaluate((el) => el === el.getRootNode().activeElement))
  await page.keyboard.press('Escape')

  // 10. 存入我的库：默认未分组；模板能筛到；再存出现更新它
  await page.getByTestId('people-category-enemy').click()
  await row(page, '测试勇者').getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '存入我的库...' }).click()
  await page.getByTestId('save-to-library').waitFor()
  await page.getByTestId('save-to-library-submit').click()
  await page.getByText(/已存到《未分组》/).waitFor()
  await clearToasts(page)
  await page.getByTestId('people-template').click()
  await page.getByTestId('template-picker').waitFor()
  await page.getByRole('button', { name: /筛选/ }).click()
  await page.getByRole('checkbox', { name: /未分组/ }).check()
  await page.getByRole('button', { name: /完成，显示/ }).click()
  check(`[${label}] 存入我的库后模板能按未分组筛到`, (await page.getByText('测试勇者').count()) >= 1)
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await clearToasts(page)
  await row(page, '测试勇者').getByRole('button', { name: /的更多操作/ }).click()
  await page.getByRole('menuitem', { name: '存入我的库...' }).click()
  await page.getByTestId('save-to-library').waitFor()
  await page.getByTestId('save-to-library-submit').click()
  await page.getByRole('radio', { name: '更新它' }).waitFor()
  check(`[${label}] 再存默认更新它`, await page.getByRole('radio', { name: '更新它' }).isChecked())
  await page.getByTestId('save-to-library-submit').click()
  await page.getByText(/已存到《未分组》/).waitFor()
}
