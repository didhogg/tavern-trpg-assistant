// P5.5 §16.10 表单返工 2b：表单按后端表单安排画（新建怪物，中文，真实官方统计）。
// 用法：SKIP_BUILD=1 node tests/e2e/library/p55-r2-form.mjs（截图 work/e2e-lib/p55-ui-shots/r2/）
import { check, failures, settle } from '../helpers.mjs'
import { openLibrary, P } from './p55-ui-common.mjs'

const { ctx, page, server, shots, tab, realErrors } = await openLibrary('r2', { width: 900, height: 760 })
await page.evaluate(async (P) => { const lib = eval(P)._s.get('app').svc().backend.library; await lib.custom.createPack('cn', { json: 'PIRATE', full: '我的包', abbreviation: 'PIR' }, { rule: 'dnd5e2014' }) }, P)
await tab('我的库')
await page.locator('[data-testid="mylib-open"]', { hasText: '我的包' }).first().click()
await page.waitForSelector('[data-testid="pack-page"]')
await page.getByTestId('pack-new-entry').click()
await page.waitForSelector('[data-testid="type-common"]'); await settle(page, 400)
await page.getByTestId('type-common').filter({ hasText: /^怪物$/ }).first().click()
await page.waitForSelector('[data-testid="new-start"]'); await settle(page, 300)
await page.getByTestId('start-next').click()
await page.waitForSelector('.trpg-modal__page:not(.is-under) [data-testid="editor"] [data-testid="entry-form"]')
await settle(page, 3000)
const main = page.getByTestId('editor-main')
const f = (n) => main.locator(`[data-field="${n}"]`)
await page.screenshot({ path: `${shots}/1-top.png` })
const sections = await main.locator('.lib-fsec').allInnerTexts()
check('分块：必填 → 常用', sections[0] === '必填' && sections[1] === '常用', sections.join(' | '))
const typeGroups = await f('type').locator('.lib-grp').count()
const typeAlt = await f('type').getByRole('button', { name: /换一种写法/ }).count()
check('类型：直接是一个控件（不套「类型」里的「类型」），有「换一种写法」', typeGroups === 0 && typeAlt === 1, JSON.stringify({ typeGroups, typeAlt }))
await f('alignment').scrollIntoViewIfNeeded()
await f('alignment').locator('.trpg-select-trigger, [role="combobox"]').first().click()
await settle(page, 400)
const opts = await page.locator('[role="option"]').allInnerTexts()
await page.screenshot({ path: `${shots}/2-alignment.png` })
await page.keyboard.press('Escape')
check('阵营：常见组合一个下拉（混乱 邪恶 / 无阵营……），最后是「自己组合…」', opts.some((o) => /混乱.*邪恶/.test(o)) && /自己组合/.test(opts[opts.length - 1] ?? ''), opts.slice(0, 6).join(' | '))
const abilityRow = await main.locator('.lib-numrow').filter({ has: page.locator('[data-field="str"]') }).locator('[data-field]').count()
check('六项属性在同一行', abilityRow >= 6, String(abilityRow))
const hpRow = await f('hp').locator('.lib-grp--row').count()
check('生命值：平均 / 公式摊在一行', hpRow === 1)
const labels = await main.locator('.lib-tfield > label').allInnerTexts()
check('字段名：AC 保留缩写，其余常用字段按作者中文资料显示', labels.some((x) => /AC/.test(x)) && labels.some((x) => /生命值/.test(x)) && labels.some((x) => /感官标签/.test(x)) && labels.some((x) => /技能/.test(x)) && !labels.some((x) => /Skills/.test(x)), labels.slice(0, 50).join(' | '))
const senseTip = await f('senseTags').locator('.lib-tip').getAttribute('title').catch(() => null)
check('感官标签有短提示', !!senseTip && /筛选/.test(senseTip), senseTip ?? '')
const strAlt = await f('str').getByRole('button', { name: /换一种写法/ }).count()
check('属性值的罕见写法（< 5%）不出菜单', strAlt === 0)
const hidden = await Promise.all(['source', 'hasToken', 'damageTags', 'traitTags', 'soundClip'].map((n) => f(n).count()))
check('来源、出版信息、自动标签不出现', hidden.every((n) => n === 0), JSON.stringify(hidden))
const moreBtn = await main.getByTestId('form-more').innerText()
check('「更多」默认收起，写着有几项', /更多（\d+ 项/.test(moreBtn), moreBtn)
const acInputs = await f('ac').locator('input').count()
check('空列表直接给一行能填（AC 不用先点「加一项」）', acInputs >= 1, String(acInputs))
check('页面没有未处理的错误（断网预期的除外）', realErrors().length === 0, realErrors().slice(0, 2).join(' | '))
await ctx.close()
server.close()
console.log(failures.length ? `FAIL ${failures.length}` : 'ALL PASS')
process.exit(failures.length ? 1 : 0)
