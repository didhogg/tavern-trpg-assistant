import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const ctx = await browser.newContext({ viewport: { width: 1200, height: 900 } })
const page = await ctx.newPage()
const logs=[]
page.on('pageerror', e => logs.push('pageerror: '+String(e.stack ?? e)))
page.on('console', m => logs.push(m.type()+': '+m.text()))
await page.goto('file:///Users/xxx/Downloads/Plotto/%E9%85%92%E9%A6%86%E5%8A%A9%E6%89%8B%E8%84%9A%E6%9C%AC/test.html')
await page.waitForTimeout(500)
console.log('fab', await page.locator('#plotto-generator-fab').count())
console.log('root', await page.locator('#plotto-generator-root').count())
console.log('overlay', await page.locator('#plotto-generator-overlay').count())
console.log('hidden before', await page.locator('#plotto-generator-overlay').getAttribute('hidden'))
await page.locator('#plotto-generator-fab').click()
await page.waitForTimeout(300)
console.log('hidden after', await page.locator('#plotto-generator-overlay').getAttribute('hidden'))
console.log('overlay html', (await page.locator('#plotto-generator-root').innerHTML()).slice(0,500))
console.log('logs', logs.slice(0,10))
