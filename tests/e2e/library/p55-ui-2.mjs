// P5.5 界面第 2 批（u7-6）：书架 ⋯ → 复制成我的（整本）；条目 ⋯ → 复制成我的（单条，选包，可当场新建包）。
// 用法：SKIP_BUILD=1 node tests/e2e/library/p55-ui-2.mjs（截图 work/e2e-lib/p55-ui-shots/2/）
import { check, failures, settle } from '../helpers.mjs'
import { openLibrary, P } from './p55-ui-common.mjs'

const { ctx, page, server, shots, closeAll, realErrors } = await openLibrary('2')
const pairsCount = () => page.evaluate(async (P) => (await eval(P)._s.get('app').svc().backend.library.bilingual.packs()).length, P)
const before = await pairsCount()

// 整本：书架搜「矿坑」→ ⋯ → 复制成我的
await page.getByTestId('shelf-search').fill('矿坑')
await settle(page, 600)
const row = page.locator('.trpg-shelf__row').first()
const bookName = (await row.locator('.lib-name').innerText()).trim()
await row.locator('.trpg-more').click()
await page.locator('.trpg-dropdown__item', { hasText: '复制成我的' }).click()
await page.waitForSelector('[data-testid="confirm-page"]')
await settle(page, 300)
await page.screenshot({ path: `${shots}/1-copy-book.png` })
const conf = await page.getByTestId('confirm-page').innerText()
await page.locator('.trpg-confirm__actions .trpg-btn--primary').click()
await page.locator('.trpg-toast', { hasText: '已复制成我的' }).waitFor()
await page.screenshot({ path: `${shots}/2-copied-toast.png` })
const afterBook = await pairsCount()
check('整本复制成我的：确认页写明「新包 / 不受原书影响 / 可复制多份」，完成后我的库多一个包', /不影响/.test(conf) && /多份/.test(conf) && afterBook === before + 1, JSON.stringify({ bookName, before, afterBook }))
// [打开] → 打开刚复制的包
await page.locator('.trpg-toast', { hasText: '已复制成我的' }).getByRole('button', { name: '打开' }).click()
await page.waitForSelector('[data-testid="pack-page"]')
await settle(page, 800)
const title = await page.locator('.trpg-modal__title').first().innerText()
await page.screenshot({ path: `${shots}/3-opened-copy.png` })
check('完成提示 [打开] → 打开刚复制的包（我的库的标题栏）', /副本/.test(title), title)
await closeAll(); await settle(page, 300)

// 单条：书架搜「玩家手册」→ 包 → 搜「火球术」→ 详情 ⋯ → 复制成我的 → 新建一个包 → 复制
await page.getByTestId('shelf-search').fill('玩家手册')
await settle(page, 600)
await page.locator('.trpg-shelf__row .lib-name').first().click()
await page.waitForSelector('[data-testid="pack-page"]')
await page.locator('[data-testid="pack-page"] input[type="search"]').fill('火球术')
await page.locator('.lib-list__row', { hasText: '火球术' }).first().click({ timeout: 120000 })
await page.waitForSelector('.lib-dtools')
await page.locator('.lib-dtools .trpg-more').click()
await page.locator('.trpg-dropdown__item', { hasText: '复制成我的' }).click()
await page.waitForSelector('[data-testid="copy-entry"]')
await settle(page, 800)
await page.screenshot({ path: `${shots}/4-copy-entry.png` })
await page.getByTestId('copy-entry-newpack').click()
await page.waitForSelector('[data-testid="newpack-page"]')
await page.getByTestId('newpack-name').fill('法术收藏')
await page.getByTestId('newpack-json').fill('SPELLBOX')
await page.getByTestId('newpack-create').click()
await page.waitForSelector('[data-testid="copy-entry"]')
await settle(page, 800)
const picked = await page.locator('[data-testid="copy-entry"] .trpg-select-trigger').innerText()
await page.screenshot({ path: `${shots}/5-copy-entry-newpack.png` })
check('当场新建包：建好退回这一页，选中新包', /法术收藏/.test(picked), picked)
await page.getByTestId('copy-entry-go').click()
await page.locator('.trpg-toast', { hasText: '复制进' }).waitFor()
const inBox = await page.evaluate(async (P) => (await eval(P)._s.get('app').svc().backend.library.custom.packs('cn')).find((p) => p.own.json === 'SPELLBOX')?.props ?? null, P)
check('单条复制：存进选的包（法术 1 条）', inBox?.spell === 1, JSON.stringify(inBox))
await page.screenshot({ path: `${shots}/6-copied-entry.png` })

check('页面没有未处理的错误（断网预期的除外）', realErrors().length === 0, realErrors().slice(0, 2).join(' | '))
await ctx.close()
server.close()
console.log(failures.length ? `FAIL ${failures.length}` : 'ALL PASS')
process.exit(failures.length ? 1 : 0)
