// P5.5 §16.10 第 4 步：作者转换、预览、取消、写回语言栏和保存重开。
import assert from 'node:assert/strict'
import { openLibrary, P } from './p55-ui-common.mjs'

const width = process.env.WIDTH ? Number(process.env.WIDTH) : 900
const { ctx, page, server, shots, tab, closeAll, svc, realErrors } = await openLibrary(width < 600 ? 'r4-narrow' : 'r4', { width, height: 760 })
page.setDefaultTimeout(40_000)
const main = page.getByTestId('editor-main')
const name = (pane) => pane.locator('[data-field="name"] input')
const editor = page.getByTestId('editor')
const paste = page.getByTestId('paste-entries')
const convert = page.getByTestId('start-convert')
const preview = async () => {
  await convert.getByTestId('convert-run').click()
  await convert.getByTestId('embedded-author').waitFor()
}
try {
  await svc((s) => s.backend.library.custom.createPack('cn', { json: 'P55CONV', full: '转换验证包', abbreviation: 'CONV' }, { rule: 'dnd5e2014' }))
  await tab('我的库')
  await page.getByTestId('mylib-open').filter({ hasText: '转换验证包' }).click()
  await page.getByTestId('pack-new-entry').click()
  await page.getByTestId('type-common').filter({ hasText: /^法术$/ }).click()
  await page.getByTestId('start-next').click()
  await name(main).fill('原草稿')
  const pasteButton = main.locator('[data-field="entries"]').getByTestId('field-paste-entries')
  if (!await pasteButton.count()) await main.getByTestId('form-more').click()
  await pasteButton.click()
  await paste.getByTestId('paste-entries-text').fill('#### 航海日志\n\n- 第一个港口\n- 第二个港口')
  await paste.getByRole('button', { name: '转换预览' }).click()
  await paste.getByTestId('paste-entries-preview').getByText('第一个港口').waitFor()
  await page.screenshot({ path: `${shots}/paste.png`, animations: 'disabled' })
  await paste.getByRole('button', { name: '加入正文' }).click()
  const heading = main.locator('[data-field="entries"]').getByTestId('block-heading')
  await heading.waitFor()
  await heading.getByRole('button', { name: '粘贴文字转成正文' }).click()
  await paste.getByTestId('paste-entries-text').fill('港口补记。')
  await paste.getByRole('button', { name: '转换预览' }).click()
  await paste.getByRole('button', { name: '加入正文' }).click()
  assert.ok((await heading.locator('textarea').evaluateAll((fields) => fields.map((f) => f.value))).includes('港口补记。'))
  assert.equal(await name(main).inputValue(), '原草稿')

  await editor.getByTestId('editor-regenerate').click()
  await convert.getByTestId('convert-sample').click()
  await preview()
  await convert.getByRole('button', { name: '取消', exact: true }).click()
  assert.equal(await name(main).inputValue(), '原草稿')
  assert.equal(await main.getByTestId('block-heading').count(), 1)

  await editor.getByTestId('editor-regenerate').click()
  await convert.getByTestId('convert-sample').click()
  await preview()
  await page.screenshot({ path: `${shots}/regenerate.png`, animations: 'disabled' })
  await convert.getByTestId('convert-go').click()
  const zhName = await name(main).inputValue()
  assert.ok(zhName && zhName !== '原草稿')
  const replaceToast = page.locator('.trpg-toast', { hasText: '已替换中文这一栏' })
  await replaceToast.getByRole('button', { name: '撤销' }).click()
  assert.equal(await name(main).inputValue(), '原草稿')
  await heading.waitFor()
  await editor.getByTestId('editor-regenerate').click()
  await convert.getByTestId('convert-sample').click()
  await preview()
  await convert.getByTestId('convert-go').click()
  assert.equal(await name(main).inputValue(), zhName)
  const other = page.getByTestId('editor-side')
  await editor.getByRole('button', { name: 'English', exact: true }).first().click()
  await name(other).fill('English draft')
  const english = await page.getByTestId('editor-regenerate-other').isVisible() ? page.getByTestId('editor-regenerate-other') : editor.getByTestId('editor-regenerate')
  await english.click()
  await convert.getByTestId('convert-sample').click()
  await preview()
  await convert.getByTestId('convert-go').click()
  const enName = await name(other).inputValue()
  assert.ok(enName && enName !== 'English draft')
  if (await editor.getByTestId('editor-views').isVisible()) await editor.getByTestId('editor-views').getByRole('button', { name: '中文', exact: true }).click()
  assert.equal(await name(main).inputValue(), zhName)

  await page.getByTestId('editor-done').click()
  await page.getByTestId('save-go').click()
  await page.locator('.trpg-toast', { hasText: `已保存「${zhName}」` }).waitFor()
  await svc((s) => s.backend.library.brewQueue.settled())
  await closeAll()
  await page.getByTestId('mylib-open').filter({ hasText: '转换验证包' }).click()
  await page.getByTestId('mine-edit').first().click()
  assert.equal(await name(main).inputValue(), zhName)
  const stored = await page.evaluate(async (P) => {
    const l = eval(P)._s.get('app').svc().backend.library
    const [zh, en] = await Promise.all([l.custom.exportPack('cn', 'p55conv'), l.custom.exportPack('en', 'p55conv')])
    return [zh.body.spell[0].name, en.body.spell[0].name]
  }, P)
  assert.deepEqual(stored, [zhName, enName])
  assert.deepEqual(realErrors(), [])
  console.log('PASS 正文及小标题内粘贴、取消、撤销、按语言替换、保存重开')
} finally {
  await ctx.close()
  server.close()
}
