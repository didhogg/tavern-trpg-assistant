// P5.5 §16.10 表单返工 2c：新建列表只列主条目；从属条目在主条目编辑页里加（职业特性挂回职业的 classFeatures）；背景介绍与图片。
// 用法：SKIP_BUILD=1 node tests/e2e/library/p55-r2c-children.mjs（截图 work/e2e-lib/p55-ui-shots/r2c/）
import { check, failures, settle } from '../helpers.mjs'
import { openLibrary, P } from './p55-ui-common.mjs'

const { ctx, page, server, shots, tab, closeAll, realErrors } = await openLibrary('r2c', { width: 900, height: 760 })
const lib = (fn, arg) => page.evaluate(async ([P, src, arg]) => (eval(src))(eval(P)._s.get('app').svc().backend.library, arg), [P, fn.toString(), arg])
const pack = await lib(async (l) => l.custom.createPack('cn', { json: 'PIRATE', full: '我的包', abbreviation: 'PIR' }, { rule: 'dnd5e2014' }))
await lib(async (l, id) => { await l.custom.saveEntry('cn', 'class', { name: '海盗', hd: { number: 1, faces: 8 }, proficiency: ['dex'], classFeatures: [] }, { pack: id }); await l.brewQueue.settled() }, pack.id)

// ① 新建列表只列主条目
await tab('我的库')
await page.locator('[data-testid="mylib-open"]', { hasText: '我的包' }).first().click()
await page.waitForSelector('[data-testid="pack-page"]')
await page.getByTestId('pack-new-entry').click()
await page.waitForSelector('[data-testid="type-item"]'); await settle(page, 400)
await page.screenshot({ path: `${shots}/1-types.png`, fullPage: true })
const items = await page.getByTestId('type-item').allInnerTexts()
const hint = await page.getByTestId('type-hint').innerText()
check('新建列表只列主条目：没有子职 / 职业特性 / 子种族 / ××描述', !items.some((t) => /^(子职|职业特性|子职特性|子种族)$|描述/.test(t)) && items.includes('职业') && items.includes('种族'), `${items.length} 类`)
check('说明从属在哪里加、背景介绍与图片在哪里写', /子职、职业特性：在「职业」的编辑页里加/.test(hint) && /背景介绍与图片/.test(hint), hint.replace(/\n/g, ' | '))
await page.getByPlaceholder(/搜类型/).fill('子职')
await settle(page, 300)
const searchHint = await page.getByTestId('type-hint').innerText()
check('搜「子职」：告诉去「职业」里加', /在「职业」的编辑页里加/.test(searchHint), searchHint.replace(/\n/g, ' | '))
await closeAll(); await settle(page, 400)

// ② 打开职业 → 属于这一条的 → 新职业特性
await page.locator('[data-testid="mylib-open"]', { hasText: '我的包' }).first().click()
await page.waitForSelector('[data-testid="mine-edit"]', { timeout: 60000 })
await page.getByTestId('mine-edit').first().click()
await page.waitForSelector('[data-testid="editor-children"]')
await settle(page, 1500)
await page.getByTestId('editor-children').scrollIntoViewIfNeeded()
await page.screenshot({ path: `${shots}/2-class-children.png` })
await page.getByTestId('editor-children').locator('[data-child="classFeature"] [data-testid="child-add"]').click()
await page.waitForSelector('.trpg-modal__page:not(.is-under) [data-testid="editor"] [data-testid="entry-form"]')
await settle(page, 2000)
const top = page.locator('.trpg-modal__page:not(.is-under) [data-testid="editor-main"]')
const pre = { className: await top.locator('[data-field="className"] input').inputValue().catch(() => ''), classSource: await top.locator('[data-field="classSource"] input').inputValue().catch(() => '') }
check('新职业特性：职业名、职业来源已照职业填好', pre.className === '海盗' && pre.classSource === 'PIRATE', JSON.stringify(pre))
await top.locator('[data-field="name"] input').first().fill('劫掠')
await top.locator('[data-field="level"] input').first().fill('1')
await settle(page, 600)
await page.screenshot({ path: `${shots}/3-feature-editor.png` })
await page.locator('.trpg-modal__page:not(.is-under) [data-testid="editor-done"]').click()
await page.waitForSelector('[data-testid="save-page"]')
await page.getByTestId('save-go').click()
await page.waitForSelector('.trpg-modal__page:not(.is-under) [data-testid="editor-children"]', { timeout: 60000 })
await settle(page, 1500)
const list = await page.locator('.trpg-modal__page:not(.is-under) [data-child="classFeature"]').innerText()
await page.screenshot({ path: `${shots}/4-back-to-class.png` })
check('存好回到职业编辑页，列表里有「1 级 · 劫掠」', /1 级 · 劫掠/.test(list), list.replace(/\n/g, ' | '))
const cls = await lib(async (l, id) => (await l.custom.exportPack('cn', id)).body.class?.[0]?.classFeatures ?? null, pack.id)
check('职业的 classFeatures 里写上了它的引用（作者 packUidClassFeature）', Array.isArray(cls) && cls.some((x) => /^劫掠\|海盗\|PIRATE\|1/i.test(typeof x === 'string' ? x : x.classFeature)), JSON.stringify(cls))
const formList = await page.locator('.trpg-modal__page:not(.is-under) [data-testid="editor-main"] [data-field="classFeatures"] input').first().inputValue().catch(() => '')
check('职业编辑页里的 classFeatures 也跟着更新了（再存职业不会盖掉）', /劫掠/.test(formList), formList)
await closeAll(); await settle(page, 400)

// ③ 种族：背景介绍与图片
await page.locator('[data-testid="mylib-open"]', { hasText: '我的包' }).first().click()
await page.waitForSelector('[data-testid="pack-page"]')
await page.getByTestId('pack-new-entry').click()
await page.waitForSelector('[data-testid="type-item"]'); await settle(page, 300)
await page.getByTestId('type-item').filter({ hasText: /^种族$/ }).first().click()
await page.waitForSelector('[data-testid="new-start"]'); await page.getByTestId('start-next').click()
await page.waitForSelector('.trpg-modal__page:not(.is-under) [data-testid="editor"] [data-testid="entry-form"]')
await settle(page, 2000)
const media = page.locator('.trpg-modal__page:not(.is-under) [data-testid="editor-main"] [data-field="fluff.images"]')
await media.scrollIntoViewIfNeeded()
await media.getByTestId('field-image').locator('input').first().fill('https://example.com/elf.png')
await media.getByTestId('field-image').locator('input').first().press('Tab')
await settle(page, 600)
await page.screenshot({ path: `${shots}/5-race-media.png` })
const ent = await page.evaluate((P) => eval(P)._s.get('modal').top.props.session && eval(P)._s.get('modal').top, P).catch(() => null)
const json = await page.evaluate(() => { const r = document.querySelector('#trpg-assistant-root').shadowRoot; return [...r.querySelectorAll('[data-testid="editor-main"] .lib-fsec')].map((e) => e.textContent) })
check('种族有「背景介绍与图片」一节', json.includes('背景介绍与图片'), json.join(' | '))
await page.locator('.trpg-modal__page:not(.is-under) .trpg-seg button', { hasText: 'JSON' }).first().click()
await settle(page, 800)
const jsonText = await page.locator('.trpg-modal__page:not(.is-under) .cm-content').innerText().catch(() => '')
check('图片存成作者的图片条目（只存网址）', /"type": "image"/.test(jsonText) && /"url": "https:\/\/example.com\/elf.png"/.test(jsonText), jsonText.replace(/\s+/g, ' ').slice(0, 200))
void ent
check('页面没有未处理的错误（断网预期的除外）', realErrors().length === 0, realErrors().slice(0, 2).join(' | '))
await ctx.close()
server.close()
console.log(failures.length ? `FAIL ${failures.length}` : 'ALL PASS')
process.exit(failures.length ? 1 : 0)
